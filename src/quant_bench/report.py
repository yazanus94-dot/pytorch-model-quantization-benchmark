from __future__ import annotations

import csv
import json
import platform
from datetime import datetime, timezone
from pathlib import Path

import torch
import torchvision

from .benchmark import BenchmarkResult


def write_machine_readable(results: list[BenchmarkResult], artifact_dir: Path, metadata: dict) -> tuple[Path, Path]:
    artifact_dir.mkdir(parents=True, exist_ok=True)
    json_path = artifact_dir / "benchmark_results.json"
    csv_path = artifact_dir / "benchmark_results.csv"

    payload = {
        "metadata": metadata,
        "results": [r.to_dict() for r in results],
    }
    json_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    rows = [r.to_dict() for r in results]
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return json_path, csv_path


def environment_metadata(**extra) -> dict:
    metadata = {
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "python": platform.python_version(),
        "platform": platform.platform(),
        "processor": platform.processor() or platform.machine(),
        "torch": torch.__version__,
        "torchvision": torchvision.__version__,
        "torch_threads": torch.get_num_threads(),
    }
    metadata.update(extra)
    return metadata


def _fmt(value: float | None, digits: int = 2) -> str:
    return "N/A" if value is None else f"{value:.{digits}f}"


def render_results_markdown(results: list[BenchmarkResult], metadata: dict) -> str:
    fp32 = next((r for r in results if r.variant == "fp32"), None)
    lines = [
        "# Quantization Benchmark Results",
        "",
        "> Generated by the benchmark runner. Values are measurements from this machine, not advertised model metadata.",
        "",
        "## Summary",
        "",
        "| Variant | Dtype | Mean latency (ms/batch) | p95 (ms) | Throughput (img/s) | Serialized size (MB) | Peak process RSS (MB) | Top-1 (%) | Accuracy Δ vs FP32 (pp) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]

    for r in results:
        delta = None if fp32 is None or fp32.top1_accuracy is None or r.top1_accuracy is None else r.top1_accuracy - fp32.top1_accuracy
        lines.append(
            f"| {r.variant} | {r.dtype} | {_fmt(r.latency_ms_mean)} | {_fmt(r.latency_ms_p95)} | "
            f"{_fmt(r.throughput_images_per_s)} | {_fmt(r.serialized_size_mb)} | {_fmt(r.peak_process_rss_mb)} | "
            f"{_fmt(r.top1_accuracy)} | {_fmt(delta)} |"
        )

    lines += [
        "",
        "## Run metadata",
        "",
    ]
    for key, value in metadata.items():
        lines.append(f"- **{key}:** `{value}`")

    lines += [
        "",
        "## Interpretation notes",
        "",
        "- Latency is CPU inference on the first validation batch after warmup; compare variants on the same machine and batch size.",
        "- `serialized size` is the byte size of `torch.save(model.state_dict())`; it is a portable proxy for model storage footprint.",
        "- `peak process RSS` is whole-process resident memory during timed inference, so it includes Python/PyTorch runtime overhead as well as model tensors.",
        "- Accuracy is measured on the selected Imagenette validation slice using the original ImageNet-1K output indices.",
        "- Dynamic INT8 is expected to have a modest effect on ResNet18 because PyTorch dynamic quantization targets supported modules such as `Linear`, while most ResNet18 compute is convolutional.",
        "- Static INT8 uses calibration data and can quantize a substantially larger fraction of the CNN inference path.",
        "",
        "## Profiler artifacts",
        "",
        "When `--profile` is enabled, Chrome traces and top-op CSVs are written under `artifacts/profiler/`.",
        "Open a trace in Perfetto/Chrome tracing or inspect the CSV to identify CPU-time and memory-heavy operations.",
        "",
    ]
    return "\n".join(lines)


def write_results_md(path: Path, results: list[BenchmarkResult], metadata: dict) -> None:
    path.write_text(render_results_markdown(results, metadata), encoding="utf-8")
